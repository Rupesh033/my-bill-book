var STORAGE_KEY = "hisaabkro-theme";
var LEGACY_STORAGE_KEY = "clothbooks-theme";
function readStoredPreference() {
	if (typeof window === "undefined") return "light";
	const value = window.localStorage.getItem(STORAGE_KEY) ?? window.localStorage.getItem(LEGACY_STORAGE_KEY);
	if (value === "light" || value === "dark" || value === "system") return value;
	return "light";
}
function systemPrefersDark() {
	if (typeof window === "undefined") return false;
	return window.matchMedia("(prefers-color-scheme: dark)").matches;
}
function applyResolvedTheme(isDark) {
	if (typeof document === "undefined") return;
	document.documentElement.classList.toggle("dark", isDark);
}
function useTheme() {
	const [mounted, setMounted] = import_react.useState(false);
	const [preference, setPreference] = import_react.useState("light");
	const [systemDark, setSystemDark] = import_react.useState(false);
	import_react.useEffect(() => {
		setMounted(true);
		setPreference(readStoredPreference());
		setSystemDark(systemPrefersDark());
		const media = window.matchMedia("(prefers-color-scheme: dark)");
		const handleChange = (event) => setSystemDark(event.matches);
		media.addEventListener("change", handleChange);
		return () => media.removeEventListener("change", handleChange);
	}, []);
	const isDark = preference === "system" ? systemDark : preference === "dark";
	import_react.useEffect(() => {
		applyResolvedTheme(isDark);
	}, [isDark]);
	const setTheme = import_react.useCallback((next) => {
		window.localStorage.setItem(STORAGE_KEY, next);
		setPreference(next);
	}, []);
	return {
		preference,
		isDark,
		setTheme,
		toggle: import_react.useCallback(() => {
			setTheme(isDark ? "light" : "dark");
		}, [isDark, setTheme]),
		mounted
	};
}
