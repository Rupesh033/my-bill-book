function filterAppNav(sections, capabilities) {
	const capabilitySet = new Set(capabilities);
	return sections.map((section) => {
		if (section.kind === "link") {
			if (section.requiredCapability && !capabilitySet.has(section.requiredCapability)) return null;
			return section;
		}
		const items = section.items.filter((item) => !item.requiredCapability || capabilitySet.has(item.requiredCapability));
		if (items.length === 0) return null;
		return {
			...section,
			items
		};
	}).filter((section) => section !== null);
}
